import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

def complex_sum_squared_with_scattering_factors_with_table(K, df):
    h = K[0]
    k = K[1]
    l = K[2]
    
    # dfから条件に一致する行をフィルタリング
    filtered_row = df[
        (df['H'] == h) &
        (df['K'] == k) &
        (df['L'] == l) 
    ]
    
    # フィルタされた行からaf0を取得し、f_qとして返す
    if not filtered_row.empty:
        f_q = filtered_row.iloc[0]['|Fc|^2']  # 一致する行が複数あった場合、最初の行を使用
        return f_q
def visualize_complex_sum(df):
    # kの範囲設定
    k1_values = np.arange(-2, 3, 1)
    k2_values = np.arange(-2, 3, 1)
    # 結果を格納する配列
    Z = np.zeros((len(k1_values), len(k2_values)))

    # k1とk2を動かしてcomplex_sumの値を計算
    for i, k1 in enumerate(k1_values):
        for j, k2 in enumerate(k2_values):
            k = np.array([0, k1, k2])
            Z[i, j] = complex_sum_squared_with_scattering_factors_with_table(k, df)

    print(Z)

    # プロット
    X, Y = np.meshgrid(k1_values, k2_values)
    fig = plt.figure()
    ax = fig.add_subplot(111, projection='3d')
    ax.plot_surface(X, Y, Z.T, cmap='viridis')

    ax.set_xlabel('k1')
    ax.set_ylabel('k2')
    ax.set_zlabel(f'|complex_sum|')
    ax.set_title(f'3D Plot of complex_sum /TlCoN2O')
    plt.show()


